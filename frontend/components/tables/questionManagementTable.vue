<script setup>
// Import Vue functions for component lifecycle, reactive state,
// and waiting for Vue's updates before accessing the table.
import { onMounted, onBeforeUnmount, ref, nextTick } from 'vue';

// Import DataTables and its Bootstrap 5 integration and styling.
import DataTable from 'datatables.net-vue3';
import DataTablesCore from 'datatables.net-bs5';
import 'datatables.net-bs5/css/dataTables.bootstrap5.css';

// Import the service that retrieves questions for the lecturer dashboard.
import { getLecturerQuestions } from '../../services/questionService';

// Register Bootstrap 5 as the DataTables styling integration.
DataTable.use(DataTablesCore);

// Emit Edit and Delete actions to the parent question management page.
const emit = defineEmits(['editQuestion', 'deleteQuestion']);

// Store the questions returned by the backend.
const questions = ref([]);

// Track loading and error states so the user receives feedback.
const loading = ref(true);
const errorMessage = ref('');

// Store the DataTables component and wrapper references.
const dataTable = ref(null);
const tableWrapper = ref(null);

// Store the unique subjects used to populate the subject dropdown.
const subjects = ref([]);

// Escape HTML characters before displaying database values in DataTables.
const escapeHtml = (value) => {
    return String(value ?? '').replace(/[&<>"']/g, (character) => {
        const htmlCharacters = {
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            '"': '&quot;',
            "'": '&#039;',
        };

        return htmlCharacters[character];
    });
};

// Extract unique subject names and sort them alphabetically.
const updateSubjects = () => {
    subjects.value = [...new Set(questions.value.map((question) => question.subjectName))]
        .filter(Boolean)
        .sort((a, b) => a.localeCompare(b));
};

// Retrieve the latest questions from the backend.
const refreshQuestions = async () => {
    errorMessage.value = '';

    try {
        questions.value = await getLecturerQuestions();
        updateSubjects();

        // Wait for Vue to update before refreshing the table.
        await nextTick();
        dataTable.value?.dt?.draw(false);
    } catch (error) {
        errorMessage.value = 'Unable to load questions. Please try again.';
        throw error;
    } finally {
        loading.value = false;
    }
};

// Handle Edit and Delete button clicks generated by DataTables.
const handleTableAction = (event) => {
    const target = event.target instanceof Element ? event.target : event.target?.parentElement;

    const button = target?.closest('button[data-action][data-question-id]');

    if (!button) {
        return;
    }

    const questionID = button.dataset.questionId;
    const question = questions.value.find((item) => String(item.questionID) === String(questionID));

    if (!question) {
        return;
    }

    if (button.dataset.action === 'edit') {
        emit('editQuestion', question);
    }

    if (button.dataset.action === 'delete') {
        emit('deleteQuestion', question);
    }
};

// Filter the Subject column using the DataTables column-search API.
const filterBySubject = async (subject) => {
    await nextTick();

    const tableApi = dataTable.value?.dt;

    if (tableApi) {
        tableApi.column(3).search(subject).draw();
    }
};

// Search the searchable columns using the custom search input.
const searchQuestions = async (searchTerm) => {
    await nextTick();

    const tableApi = dataTable.value?.dt;

    if (tableApi) {
        tableApi.search(searchTerm).draw();
    }
};

// Expose the question data and functions to the parent page.
defineExpose({
    questions,
    subjects,
    filterBySubject,
    searchQuestions,
    refreshQuestions,
});

// Retrieve questions and attach the delegated click listener.
onMounted(async () => {
    tableWrapper.value?.addEventListener('click', handleTableAction);

    try {
        await refreshQuestions();
    } catch {
        // The refresh method already sets the error message.
    }
});

// Remove the click listener when the component is destroyed.
onBeforeUnmount(() => {
    tableWrapper.value?.removeEventListener('click', handleTableAction);
});

// Define the columns displayed in the question management table.
const columns = [
    {
        data: 'question',
        title: 'Question',
    },
    {
        data: 'answers',
        title: 'Answers',
        defaultContent: '',
        render: (answers, type) => {
            if (!Array.isArray(answers)) {
                return '';
            }

            const answerTexts = answers.map((answer) => answer.answerText);

            if (type !== 'display') {
                return answerTexts.join(' | ');
            }

            return answerTexts.map((answer) => escapeHtml(answer)).join(' | ');
        },
    },
    {
        data: 'correctAnswer',
        title: 'Correct Answer',
        defaultContent: '',
        render: (value, type) => {
            if (value === null || value === undefined) {
                return '';
            }

            return type === 'display' ? escapeHtml(value) : value;
        },
    },
    {
        data: 'subjectName',
        title: 'Subject',
        defaultContent: '',
    },
    {
        data: 'percentageCorrect',
        title: 'Percentage Correct',
        render: (value, type) => {
            if (value === null || value === undefined) {
                return '';
            }

            return type === 'display' ? `${value}%` : value;
        },
    },
    {
        data: null,
        title: 'Actions',
        orderable: false,
        searchable: false,
        defaultContent: '',
        render: (data, type, row) => {
            if (type !== 'display') {
                return '';
            }

            const questionID = escapeHtml(row.questionID);

            return `
                <button
                    type="button"
                    class="btn btn-sm tableEditButton tableActionButton me-2"
                    data-action="edit"
                    data-question-id="${questionID}"
                    aria-label="Edit question"
                >
                    Edit
                </button>
                <button
                    type="button"
                    class="btn btn-sm tableDeleteButton tableActionButton"
                    data-action="delete"
                    data-question-id="${questionID}"
                    aria-label="Delete question"
                >
                    Delete
                </button>
            `;
        },
    },
];

// Configure DataTables searching, sorting and pagination.
const tableOptions = {
    searching: true,
    ordering: true,
    paging: true,
    pageLength: 5,
    lengthChange: false,
    order: [[0, 'asc']],
    autoWidth: false,
    layout: {
        topStart: null,
        topEnd: null,
        bottomStart: 'info',
        bottomEnd: 'paging',
    },
    language: {
        emptyTable: 'No questions to display.',
        zeroRecords: 'No questions match your filters.',
        search: 'Search questions:',
    },
};
</script>

<template>
    <div ref="tableWrapper" class="questionTableWrapper">
        <!-- Announce the loading status to users and assistive technologies. -->
        <p v-if="loading" role="status">Loading questions...</p>

        <!-- Display an accessible error message if loading fails. -->
        <p v-else-if="errorMessage" role="alert">
            {{ errorMessage }}
        </p>

        <!-- Display the table after loading completes successfully. -->
        <div v-else class="tableResponsive">
            <DataTable
                ref="dataTable"
                :columns="columns"
                :data="questions"
                :options="tableOptions"
                class="table table-sm table-striped table-hover align-middle mb-0"
            />
        </div>
    </div>
</template>

